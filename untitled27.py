import streamlit as st

st.set_page_config(page_title="Mi Block de Notas", page_icon="📝")

st.title("📝 Block de Notas Rápido")
st.write("Escribe lo que quieras abajo. Los cambios se guardan automáticamente en tu sesión.")

# Área de texto interactiva
nota = st.text_area(
    "Escribe tus apuntes aquí:",
    value="Escribe tus ideas, borradores o recordatorios...",
    height=300
)

# Un pequeño contador de palabras y caracteres en tiempo real
palabras = len(nota.split()) if nota else 0
caracteres = len(nota)

st.caption(f"📊 Estadísticas: {palabras} palabras | {caracteres} caracteres")